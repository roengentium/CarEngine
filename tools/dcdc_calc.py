#!/usr/bin/env python3
"""First-pass sizing for an isolated, center-tapped full-bridge DC-DC (96V or Leaf-pack input -> 14V).
Run:  python3 tools/dcdc_calc.py > docs/DESIGN_CALC.md
All numbers are starting points for simulation/bench work, not a finished design."""
import math

def size(name, vin_min, vin_max, vout=14.0, pout=500.0, fsw=100e3,
         deff_max=0.80, vdrop=0.30, ripple_frac=0.30, vripple=0.05):
    iout = pout / vout
    ratio = math.floor(vin_min * deff_max / (vout + vdrop))      # Np:Ns (integer, per CT half)
    vsec_min, vsec_max = vin_min / ratio, vin_max / ratio
    d_at_min = (vout + vdrop) / vsec_min
    d_at_max = (vout + vdrop) / vsec_max
    ts = 1 / fsw
    di = ripple_frac * iout
    lo = (vsec_max - vout - vdrop) * (d_at_max * ts / 2) / di
    cout = di / (8 * 2 * fsw * vripple)                           # ideal-cap ripple, ESR will dominate
    ipri_rms = iout / ratio * math.sqrt(d_at_min) * 1.1           # +10% magnetizing/ringing allowance
    isec_rms = iout * math.sqrt(0.5)                              # per CT winding
    return dict(name=name, vin_min=vin_min, vin_max=vin_max, vout=vout, pout=pout, iout=iout,
                fsw=fsw, ratio=ratio, d_at_min=d_at_min, d_at_max=d_at_max, lo=lo, cout=cout,
                ipri_rms=ipri_rms, isec_rms=isec_rms,
                vds_pri=vin_max * 1.3, vds_sec=2 * vsec_max * 1.3)

profiles = [
    # 96S x 3.0-4.2 V/cell = 288-403 V (design envelope; check LBC cutoff + charger limits)
    size("Leaf 2022 pack (96S, 288-403 V envelope)", 288, 403),
    # original project label "96V": 96 V +/-15%
    size("Original 96 V bench/low-voltage profile (82-110 V)", 82, 110),
]
print("# Sizing results (generated by tools/dcdc_calc.py)\n")
print("Topology assumed: isolated full-bridge, center-tapped secondary, 14.0 V out, 500 W, 100 kHz.")
print("Change defaults in the script (vout, pout, fsw) and re-run.\n")
rows = [("Input range (V)", lambda p: f"{p['vin_min']}-{p['vin_max']}"),
        ("Output", lambda p: f"{p['vout']} V / {p['iout']:.1f} A / {p['pout']:.0f} W"),
        ("Turns ratio Np:Ns:Ns", lambda p: f"{p['ratio']}:1:1"),
        ("Effective duty at Vin_min / Vin_max", lambda p: f"{p['d_at_min']:.2f} / {p['d_at_max']:.2f}"),
        ("Output inductor (min, 30% ripple)", lambda p: f"{p['lo']*1e6:.1f} uH, rated >= {p['iout']*1.3:.0f} A"),
        ("Output cap (ripple only)", lambda p: f"{p['cout']*1e6:.0f} uF min (ESR dominates)"),
        ("Primary RMS current (approx)", lambda p: f"{p['ipri_rms']:.1f} A"),
        ("Secondary RMS per winding", lambda p: f"{p['isec_rms']:.1f} A"),
        ("Primary FET Vds rating (x1.3)", lambda p: f">= {p['vds_pri']:.0f} V"),
        ("Secondary FET Vds rating (x1.3)", lambda p: f">= {p['vds_sec']:.0f} V")]
print("| Parameter | " + " | ".join(p["name"] for p in profiles) + " |")
print("|---|" + "---|" * len(profiles))
for label, f in rows:
    print(f"| {label} | " + " | ".join(f(p) for p in profiles) + " |")
print("\nNotes: duty is limited to 0.8 at minimum input; 0.3 V allowance for secondary drops; "
      "no resonant/ZVS tuning, leakage inductance or thermal derating included.")
